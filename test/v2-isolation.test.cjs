"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..");
const js=fs.readFileSync(path.join(root,"v2/v2.js"),"utf8");
const persistence=fs.readFileSync(path.join(root,"v2/persistence.js"),"utf8");
const server=fs.readFileSync(path.join(root,"server.cjs"),"utf8");
const login=fs.readFileSync(path.join(root,"login.html"),"utf8");
const selector=fs.readFileSync(path.join(root,"version-select.html"),"utf8");
assert.match(login,/location\.href="version-select\.html"/,"login must lead to the version selector");
assert.match(selector,/href="dashboard\.html"/,"v1 must remain directly selectable");
assert.match(selector,/href="v2\/index\.html"/,"v2 must be selectable");
assert.match(js,/DATA_KEY="shumoosV2:sandbox:v1"/,"v2 must use its isolated namespace");
assert.doesNotMatch(js,/fetch\([^\n]*api\/storage[^\n]*method\s*:\s*["']POST/i,"v2 must never post to v1 storage");
assert.doesNotMatch(js,/localStorage\.(setItem|removeItem)\(["']misad(?!Session)/,"v2 must never mutate v1 data keys");
assert.doesNotMatch(persistence,/api\/storage/,"v2 persistence must never call the v1 storage API");
assert.match(persistence,/api\/v2\/state/,"v2 must persist through its isolated API");
assert.doesNotMatch(persistence,/function save\(/,"v2 UI must not expose bulk state writes");
assert.match(persistence,/api\/v2\/command/,"v2 mutations must use audited commands");
assert.match(server,/v2Api\.handle\(req, res, pathname\)/,"the server must route v2 separately");
assert.match(server,/V2_EPHEMERAL_PREVIEW/);assert.match(server,/preferredDataDir\.startsWith\("\/tmp\/"\)/,"ephemeral preview must be explicit and limited to tmp");
console.log("v2 isolation checks passed");
